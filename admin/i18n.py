def detect(accept_language: str | None) -> str:
    """Pick the best supported locale from an Accept-Language header."""
    if not accept_language:
        return "en"
    candidates: list[tuple[str, float]] = []
    for part in accept_language.split(","):
        part = part.strip()
        if ";q=" in part:
            lang, q_str = part.split(";q=", 1)
            try:
                q = float(q_str)
            except ValueError:
                q = 0.0
        else:
            lang, q = part, 1.0
        candidates.append((lang.strip().lower(), q))
    candidates.sort(key=lambda x: -x[1])
    for lang, _ in candidates:
        code = lang[:2]
        if code in T:
            return code
    return "en"
